// ================= 组合展开 =================
const SPEAKERS = Object.keys(VOICES);
const db = {};
const seen = new Set();
let totalChars = 0;

function addLine(key, text, ctx) {
  const sig = key + '|' + text;
  if (seen.has(sig)) return;
  seen.add(sig);
  db[key].push(ctx === 'any' ? { t: text } : { t: text, c: ctx });
  totalChars += text.length;
}

// 每位角色的基础台词来源(身份台词也纳入)
for (const key of SPEAKERS) {
  db[key] = [];
  const V = VOICES[key];
  const tail = () => (rnd() < 0.5 ? pick(V.tails) : '');
  const mood = () => (rnd() < 0.3 ? pick(V.mood) : '');
  const openFor = (ctx) => (rnd() < 0.75 ? pick(OPENERS[ctx]) : '');

  // 1) 时辰/天气 × 职业日常
  const jobs = [...(JOB_EXTRA[key] || [])];
  if (key.startsWith('v')) jobs.push(...VILLAGERS[+key.slice(1)].lines.map((l) => l.replace(/[。!?]$/, '')));
  for (const ctx of ['dawn', 'day', 'dusk', 'night']) {
    for (const j of jobs) {
      for (let k = 0; k < 2; k++) {
        addLine(key, `${openFor(ctx)}${mood()}${j}。${tail()}`, ctx);
      }
    }
  }
  // 2) 天气专属
  for (const w of ['clear', 'rain', 'storm']) {
    for (const f of WEATHER_TALK[w]) {
      for (let k = 0; k < 3; k++) addLine(key, `${openFor(w)}${mood()}${f}。${tail()}`, w);
    }
  }
  // 2b) 季节专属(标签 spring/summer/autumn/winter)
  for (const [sn, lines] of Object.entries(SEASON_TALK)) {
    for (const f of lines) {
      for (let k = 0; k < 3; k++) {
        const ctx2 = pick(['dawn', 'day', 'dusk', 'night']);
        addLine(key, `${rnd() < 0.5 ? pick(OPENERS[ctx2]) : ''}${mood()}${f}。${tail()}`, sn);
      }
    }
  }
  // 2c) 节庆专属(标签 market/fullmoon/wolfmoon/harvest)
  for (const [fk, lines] of Object.entries(FESTIVAL_TALK)) {
    for (const f of lines) {
      for (let k = 0; k < 3; k++) addLine(key, `${mood()}${f}。${tail()}`, fk);
    }
  }
  // 3) 八卦其他角色(不八卦自己):每条谈资用 4 种不同句式
  for (const other of SPEAKERS) {
    if (other === key) continue;
    for (const fact of FACTS[other]) {
      const frames = [...GOSSIP_FRAMES].sort(() => rnd() - 0.5).slice(0, 4);
      for (const frame of frames) {
        addLine(key, `${mood()}${frame.replace('{name}', NAMES[other]).replace('{fact}', fact)}${tail()}`);
      }
    }
  }
  // 4) 世界传闻:每条传闻 4 种口吻
  for (const r of RUMORS) {
    const frames = [...RUMOR_FRAMES].sort(() => rnd() - 0.5).slice(0, 4);
    for (const frame of frames) {
      addLine(key, `${mood()}${frame.replace('{r}', r)}${tail()}`);
    }
  }
  // 5) 地点谈资:每条 2 种句式
  for (const [p, facts] of Object.entries(PLACES)) {
    for (const f of facts) {
      const frames = [...PLACE_FRAMES].sort(() => rnd() - 0.5).slice(0, 2);
      for (const frame of frames) {
        addLine(key, `${frame.replace('{p}', p).replace('{f}', f)}${tail()}`);
      }
    }
  }
  // 6) 任务阶段议论(带 q0..q8 标签)
  STAGE_TOPICS.forEach((topics, stage) => {
    for (const t of topics) {
      for (let k = 0; k < 2; k++) {
        const frame = pick(STAGE_FRAMES).replace('{t}', t).replace('{who}', pick(WHO));
        addLine(key, `${mood()}${frame}${tail()}`, `q${stage}`);
      }
    }
  });
  // 7) 谚语
  for (const p of PROVERBS) {
    addLine(key, `${mood()}${pick(PROVERB_FRAMES).replace('{p}', p)}${tail()}`);
  }
  // 8) 回忆
  for (const mem of MEMORIES[key] || []) {
    for (const frame of ['说起来,{m}……', '有时想起,{m}。', '{m}——一晃这么多年了。', '跟你说件旧事:{m}。']) {
      addLine(key, `${mood()}${frame.replace('{m}', mem)}${tail()}`);
    }
  }
  // 9) 称呼玩家的寒暄(时辰)
  for (const ctx of ['dawn', 'day', 'dusk', 'night']) {
    for (const o of OPENERS[ctx]) {
      addLine(key, `${o}${V.addr},${pick(['又见面了', '有何贵干', '今天气色不错', '路上顺利吗', '别来无恙'])}。${tail()}`, ctx);
    }
  }
}

